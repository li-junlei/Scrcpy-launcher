const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('dist/file-manager.js', 'utf8');
const nodes = Object.fromEntries(['file-progress', 'transfer-progress', 'file-progress-text', 'total-progress-text', 'current-file', 'file-speed', 'total-speed', 'transfer-message'].map(id => [id, {}]));
let now = 0;
const context = { $: id => nodes[id], performance: { now: () => now } };
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function sizeText('), source.indexOf('function render(side)')) + source.slice(source.indexOf('function renderTransferProgress('), source.indexOf("$('device').onchange")), context);
context.renderTransferProgress({file_name:'中文.bin', file_path:'/dir/中文.bin', file_bytes:256, file_size:1024, total_bytes:1280, total_size:2048, file_complete:false});
assert.equal(nodes['file-progress'].value, 25);
assert.equal(nodes['transfer-progress'].value, 62.5);
assert.equal(nodes['current-file'].textContent, '当前文件：中文.bin');
assert.equal(nodes['current-file'].title, '/dir/中文.bin');
context.renderTransferProgress({file_name:'empty',file_path:'/empty',file_bytes:0,file_size:0,total_bytes:1280,total_size:2048,file_complete:true});
assert.equal(nodes['file-progress'].value,100);
assert.equal(nodes['transfer-progress'].value,62.5);
console.log('File progress rendering checks passed.');

vm.runInContext('globalThis.meter = new TransferSpeed()', context);
assert.equal(context.meter.sample(1024, 1000), 1024);
assert.equal(context.meter.sample(2048, 2000), 1024);
assert.equal(context.meter.sample(2048, 3000), 0);
context.meter.reset(4000);
assert.equal(context.meter.sample(512, 4500), 1024);
assert.equal(context.meter.sample(512, 5500), 0);
now = 1000;
context.renderTransferProgress({file_name:'test',file_path:'/test',file_bytes:1024,file_size:2048,total_bytes:2048,total_size:4096,file_complete:false});
now = 1500;
context.renderTransferProgress({file_name:'test',file_path:'/test',file_bytes:1536,file_size:2048,total_bytes:2560,total_size:4096,file_complete:false});
assert.equal(nodes['file-speed'].textContent, '1.0 KB/s');
now = 3000;
context.renderTransferSpeed();
assert.equal(nodes['file-speed'].textContent, '0 B/s');
assert.equal(nodes['total-speed'].textContent, '0 B/s');

vm.runInContext(source.slice(source.indexOf('function handleFileManagerClose('), source.indexOf('(async () => {', source.indexOf('function handleFileManagerClose('))), context);
let prevented = false;
context.busy = false;
context.handleFileManagerClose({preventDefault:()=>{prevented=true;}});
assert.equal(prevented,false,'空闲窗口必须允许关闭');
context.busy = true;
context.handleFileManagerClose({preventDefault:()=>{prevented=true;}});
assert.equal(prevented,true,'传输期间防误关');
const capability = JSON.parse(fs.readFileSync('capabilities/file-manager.json','utf8'));
assert.deepEqual(capability.windows,['file-manager']);
assert(capability.permissions.includes('core:window:allow-destroy'),'Tauri onCloseRequested 默认关闭依赖 destroy 权限');
console.log('Speed sampling, idle reset, close guard and capability checks passed.');
